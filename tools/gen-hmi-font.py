#!/usr/bin/env python3
"""Generate the shared HMI bitmap-font atlas.

Renders ASCII 32..126 plus a small set of operator symbols with
DejaVuSansMono through PIL and emits two artifacts that MUST stay in
sync (regenerate both together):

  src/hmi/font-atlas.ts                 -- advance metrics for web layout
  <tether>/examples/hmi_font_atlas.hpp  -- glyph bitmaps + metrics for
                                           the native Vulkan renderer

Convention shared by both backends: a `text` op's (x, y) is the
BASELINE origin of the first glyph's pen; `size` is the em size in
scene units; bearings/advance are em units (px / FONT_SIZE).

Usage:  python3 tools/gen-hmi-font.py [--tether-root ../Tether]
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
FONT_SIZE = 16
CELL_W, CELL_H = 14, 24
BASELINE_Y = CELL_H - 4          # leave room for descenders below
ATLAS_W = 256
ASCII_FIRST, ASCII_LAST = 32, 126
EXTRA = "°µ±²³×÷·—–…■●▲▼←→↑↓≈≤≥≠∞ΩαβγΔΣπτφω"

REPO = Path(__file__).resolve().parent.parent


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tether-root", default=str(REPO.parent / "Tether"))
    args = ap.parse_args()

    chars = [chr(c) for c in range(ASCII_FIRST, ASCII_LAST + 1)]
    for ch in EXTRA:
        if ch not in chars:
            chars.append(ch)

    font = ImageFont.truetype(FONT_PATH, FONT_SIZE)
    ascent, _descent = font.getmetrics()

    # draw origin so that the font baseline lands on BASELINE_Y
    draw_y = BASELINE_Y - ascent

    glyphs = []
    atlas = Image.new("L", (ATLAS_W, 8192), 0)
    cursor_x = 1
    cursor_y = 1
    row_h = 0
    for ch in chars:
        img = Image.new("L", (CELL_W, CELL_H), 0)
        d = ImageDraw.Draw(img)
        d.text((1, draw_y), ch, font=font, fill=255)
        bbox = img.getbbox()
        adv = font.getlength(ch)
        if bbox is None:                       # space and friends
            glyphs.append({"ch": ch, "ink": None, "adv": adv})
            continue
        x0, y0, x1, y1 = bbox
        ink = img.crop(bbox)
        gw, gh = ink.size
        if cursor_x + gw + 1 > ATLAS_W:
            cursor_x = 1
            cursor_y += row_h + 1
            row_h = 0
        atlas.paste(ink, (cursor_x, cursor_y))
        glyphs.append({
            "ch": ch, "ink": (cursor_x, cursor_y, gw, gh),
            # bearings em units, origin = pen position at baseline
            "ax": (x0 - 1) / FONT_SIZE,
            "ay": (y0 - BASELINE_Y) / FONT_SIZE,
            "adv": adv / FONT_SIZE,
        })
        cursor_x += gw + 1
        row_h = max(row_h, gh)

    atlas = atlas.crop((0, 0, ATLAS_W, cursor_y + row_h + 1))
    aw, ah = atlas.size
    px = atlas.tobytes()

    # --- TS artifact: advance metrics ------------------------------------
    ts = REPO / "src/hmi/font-atlas.ts"
    ts.parent.mkdir(parents=True, exist_ok=True)
    adv_pairs = ", ".join(
        f"{g['ch']!r}:{g['adv']:.4f}" for g in glyphs if g["ink"]
    )
    ts.write_text(f"""/**
 * Generated by tools/gen-hmi-font.py — DO NOT EDIT.
 * DejaVuSansMono {FONT_SIZE}px advance metrics (em units) shared by the
 * web text layout and the native Vulkan HMI renderer so both backends
 * position strings identically. Glyph bitmaps live in the C++ header
 * examples/hmi_font_atlas.hpp (Tether repo).
 */
export const HMI_FONT_EM = {FONT_SIZE};

/** advance of `s` at font size `size` (scene units) */
export function hmiTextWidth(s: string, size: number): number {{
  const ADV: Record<string, number> = {{{adv_pairs}}};
  const FALLBACK_ADV = 0.6025;
  let w = 0;
  for (const ch of s) w += (ADV[ch] ?? FALLBACK_ADV) * size;
  return w;
}}
""")

    # --- C++ artifact -----------------------------------------------------
    out = Path(args.tether_root) / "examples/hmi_font_atlas.hpp"
    out.parent.mkdir(parents=True, exist_ok=True)
    gl = [
        "    {0x%04x, %d, %d, %d, %d, %.5ff, %.5ff, %.5ff}," % (
            ord(g["ch"]), *g["ink"], g["ax"], g["ay"], g["adv"])
        for g in glyphs if g["ink"]
    ]
    px_rows = ",\n".join(
        "    " + ",".join(str(b) for b in px[y * aw:(y + 1) * aw])
        for y in range(ah)
    )
    out.write_text(f"""// Generated by TetherWebUI tools/gen-hmi-font.py — DO NOT EDIT.
// DejaVuSansMono {FONT_SIZE}px bitmap atlas for the Vulkan HMI renderer.
// Glyph rects are tight ink bounds inside a {aw}x{ah} alpha atlas;
// bearings/advance are em units (multiply by the scene font size).
// Regenerate: cd TetherWebUI && python3 tools/gen-hmi-font.py
#pragma once
#include <cstdint>

namespace hmi_font {{

inline constexpr int kAtlasW = {aw};
inline constexpr int kAtlasH = {ah};
inline constexpr float kFontEm = {float(FONT_SIZE)};

struct Glyph {{
  uint32_t code;    // unicode codepoint
  uint16_t u, v;    // atlas origin of the tight ink rect
  uint16_t w, h;    // ink size in texels
  float ax, ay;     // bearings, em units (ay<0 = above baseline)
  float adv;        // advance, em units
}};

inline constexpr Glyph kGlyphs[] = {{
{chr(10).join(gl)}
}};
inline constexpr int kGlyphCount = sizeof(kGlyphs) / sizeof(kGlyphs[0]);

/* atlas alpha plane: 0=transparent .. 255=ink */
inline constexpr uint8_t kAtlas[] = {{
{px_rows}
}};

inline const Glyph* findGlyph(uint32_t cp) {{
  for (const auto& g : kGlyphs) if (g.code == cp) return &g;
  return nullptr;
}}

}} // namespace hmi_font
""")
    print(f"wrote {ts}")
    print(f"wrote {out}  ({sum(1 for g in glyphs if g['ink'])} glyphs, atlas {aw}x{ah})")


if __name__ == "__main__":
    main()
